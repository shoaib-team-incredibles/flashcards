#!/usr/bin/env node
// Copies the French and English decks, French guide and shared logic from the web app into the iOS app.
// Run after editing anything in ../decks/ or ../src/lib/french-core.ts:
//   node mobile/scripts/sync-french.mjs
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const mobile = join(dirname(fileURLToPath(import.meta.url)), '..')
const root = join(mobile, '..')
const out = join(mobile, 'src/data/french')
mkdirSync(out, { recursive: true })

for (const k of ['vocab', 'expressions', 'grammar']) copyFileSync(join(root, `decks/french-${k}.json`), join(out, `${k}.json`))
const guide = readFileSync(join(root, 'decks/french-guide.md'), 'utf8').replace(/^# .*\n+/, '')
writeFileSync(join(out, 'guide.ts'), `// Generated by scripts/sync-french.mjs from decks/french-guide.md — do not edit.\nexport const FRENCH_GUIDE = ${JSON.stringify(guide)};\n`)
const english = join(mobile, 'src/data/english')
mkdirSync(english, { recursive: true })
copyFileSync(join(root, 'decks/english-vocab.json'), join(english, 'vocab.json'))
copyFileSync(join(root, 'src/lib/french-core.ts'), join(mobile, 'src/lib/french-core.ts'))
console.log('French and English content synced to', out, 'and', english)
